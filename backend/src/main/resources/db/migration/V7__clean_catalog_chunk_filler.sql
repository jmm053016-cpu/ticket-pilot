-- 清理服装目录单品 chunk 里"为凑关键词硬加的填充语"：「，价格刚好<价格>元。」
--
-- 背景（2026-11-03 实测）：每条单品 chunk 结尾都写了「价格刚好699元」这种句子，
-- 于是用户问「价格刚好699的衣服是什么」时，价格 259 / 229 的条目因为同样含「价格刚好」
-- 而一起被召回，答案里混进无关商品。数据本身不该带这种额外的关键词噪音。
--
-- 修法：只删掉句尾这一段，其余字段不动（商品编号 / 名称 / 品类 / 价格都保留）。
-- 注意：不要改 V5（会破坏已应用库的 Flyway checksum），必须用新版本迁移。

UPDATE knowledge_chunks
SET content = REGEXP_REPLACE(content, '，价格刚好[0-9.]+元。$', '。')
WHERE content REGEXP '，价格刚好[0-9.]+元。$';
